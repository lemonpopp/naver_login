CREATE TABLE NLOGIN(
	NO NUMBER PRIMARY KEY, 
	ID VARCHAR2(500) NOT NULL UNIQUE,
	PW VARCHAR2(500) NOT NULL,
	EMAIL VARCHAR2(100) UNIQUE,
	NAME VARCHAR2(500) NOT NULL,
	BIRTH NUMBER NOT NULL,
	MOB VARCHAR2(100) NOT NULL,
	GENDER VARCHAR2(100) NOT NULL,
	NATION VARCHAR2(100) NOT NULL,
	TEL VARCHAR2(500) NOT NULL,
	REQUIREDTERMS VARCHAR(10) CHECK (REQUIREDTERMS IN ('Y', 'N')) NOT NULL,
	NAMETERMS VARCHAR(10) CHECK (NAMETERMS IN ('Y', 'N')) NOT NULL,
	LOCATIONTERMS VARCHAR(10) CHECK (LOCATIONTERMS IN ('Y', 'N')) NOT NULL,
	PESONALTERMS VARCHAR(10) CHECK (PESONALTERMS IN ('Y', 'N')) NOT NULL
);

